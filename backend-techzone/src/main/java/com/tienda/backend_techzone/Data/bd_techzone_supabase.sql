-- ==============================================================
--  7 · AUDITORÍA (solo lectura desde el panel de administración)
-- ==============================================================

CREATE TABLE registro_acceso (
    id_acceso   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario  BIGINT,                    -- NULL si el correo no existia
    correo      VARCHAR(100),              -- se conserva aunque borren al usuario
    fecha_hora  TIMESTAMP NOT NULL DEFAULT now(),
    ip          VARCHAR(45),
    agente      VARCHAR(255),
    exitoso     BOOLEAN  NOT NULL,
    motivo      VARCHAR(40),               -- ok | clave_incorrecta | usuario_inexistente | cuenta_bloqueada
    PRIMARY KEY (id_acceso),
    CONSTRAINT fk_acceso_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE SET NULL
);

CREATE TABLE registro_auditoria (
    id_auditoria  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    BIGINT,
    fecha_hora    TIMESTAMP NOT NULL DEFAULT now(),
    modulo        VARCHAR(50) NOT NULL,    -- producto | categoria | usuario | venta | ayuda
    accion        VARCHAR(30) NOT NULL,    -- CREAR | ACTUALIZAR | ELIMINAR | LOGIN | LOGOUT | DENEGADO
    descripcion   VARCHAR(255),
    datos_previos TEXT,                    -- JSON antes del cambio
    datos_nuevos  TEXT,                    -- JSON despues del cambio
    ip            VARCHAR(45) NOT NULL DEFAULT '127.0.0.1',
    PRIMARY KEY (id_auditoria),
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE SET NULL
);


-- ==============================================================
--  8 · CENTRO DE AYUDA (contenido editable por el administrador)
