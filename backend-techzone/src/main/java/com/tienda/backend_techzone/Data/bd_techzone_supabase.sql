-- ==============================================================
--  2 · TABLAS DE REFERENCIA (sin dependencias)
-- ==============================================================

CREATE TABLE ubigeo (
    id_ubigeo     BIGINT NOT NULL,
    departamento  VARCHAR(50),
    provincia     VARCHAR(50),
    distrito      VARCHAR(50),
    vigente       BOOLEAN,
    PRIMARY KEY (id_ubigeo)
);

CREATE TABLE tipo_documento (
    id_tipo_documento BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR(50),
    vigente           BOOLEAN,
    PRIMARY KEY (id_tipo_documento)
);

CREATE TABLE rol (
    id_rol   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre   VARCHAR(20),
    vigente  BOOLEAN,
    PRIMARY KEY (id_rol)
);

CREATE TABLE marca (
    id_marca  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre    VARCHAR(50),
    logo_url  VARCHAR(500),
    vigente   BOOLEAN,
    PRIMARY KEY (id_marca)
);

CREATE TABLE categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(50),
    vigente      BOOLEAN,
    PRIMARY KEY (id_categoria)
);

CREATE TABLE medio_pago (
    id_medio_pago BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR(50),
    instrucciones VARCHAR(300),
    vigente       BOOLEAN,
    PRIMARY KEY (id_medio_pago)
);


-- ==============================================================
--  3 · TABLAS DE PERSONAS Y USUARIOS
-- ==============================================================

CREATE TABLE persona (
    id_persona         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombres            VARCHAR(100),
    apellido_paterno   VARCHAR(50),
    apellido_materno   VARCHAR(50),
    id_tipo_documento  BIGINT,
    numero_documento   VARCHAR(20),
    telefono           VARCHAR(15),
    direccion          VARCHAR(255),
    referencia         VARCHAR(255),
    id_ubigeo          BIGINT,
    fecha_nacimiento   DATE,
    fecha_registro     TIMESTAMP,
    vigente            BOOLEAN,
    PRIMARY KEY (id_persona),
    CONSTRAINT uk_persona_documento UNIQUE (numero_documento),
    CONSTRAINT uk_persona_telefono UNIQUE (telefono),
    CONSTRAINT fk_persona_tipo_doc FOREIGN KEY (id_tipo_documento)
        REFERENCES tipo_documento (id_tipo_documento) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_persona_ubigeo FOREIGN KEY (id_ubigeo)
        REFERENCES ubigeo (id_ubigeo) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE proveedor (
    id_proveedor      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    razon_social      VARCHAR(150),
    id_tipo_documento BIGINT,
    numero_documento  VARCHAR(20),
    telefono_contacto VARCHAR(20),
    correo            VARCHAR(100),
    nombre_encargado  VARCHAR(150),
    vigente           BOOLEAN,
    PRIMARY KEY (id_proveedor),
    CONSTRAINT uk_proveedor_documento UNIQUE (numero_documento),
    CONSTRAINT uk_proveedor_correo UNIQUE (correo),
    CONSTRAINT uk_proveedor_telefono UNIQUE (telefono_contacto),
    CONSTRAINT fk_proveedor_tipo_doc FOREIGN KEY (id_tipo_documento)
        REFERENCES tipo_documento (id_tipo_documento) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE cliente (
    id_cliente          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona          BIGINT,
    fecha_ultima_compra TIMESTAMP,
    total_gastado       NUMERIC(10,2),
    vigente             BOOLEAN,
    PRIMARY KEY (id_cliente),
    CONSTRAINT fk_cliente_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_cliente_total CHECK (total_gastado >= 0)
);

CREATE TABLE empleado (
    id_empleado    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona     BIGINT,
    fecha_contrato DATE,
    salario        NUMERIC(10,2),
    vigente        BOOLEAN,
    PRIMARY KEY (id_empleado),
    CONSTRAINT fk_empleado_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_empleado_salario CHECK (salario >= 0)
);

CREATE TABLE usuario (
    id_usuario          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona          BIGINT,
    id_rol              BIGINT,
    correo              VARCHAR(100),
    contrasena          VARCHAR(100),
    fecha_ultimo_acceso TIMESTAMP,
    estado              VARCHAR(20),
    -- Trazabilidad y control de fuerza bruta
    fecha_creacion      TIMESTAMP   NOT NULL DEFAULT now(),
    intentos_fallidos   SMALLINT    NOT NULL DEFAULT 0,
    bloqueado_hasta     TIMESTAMP   NULL,
    PRIMARY KEY (id_usuario),
    CONSTRAINT uk_usuario_correo  UNIQUE (correo),
    CONSTRAINT uk_usuario_persona UNIQUE (id_persona),
    CONSTRAINT fk_usuario_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol)
        REFERENCES rol (id_rol) ON DELETE RESTRICT ON UPDATE CASCADE
);


-- ==============================================================
--  4 · CATÁLOGOS DE PRODUCTO
-- ==============================================================

CREATE TABLE producto (
    id_producto     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_marca        BIGINT,
    id_categoria    BIGINT,
    codigo_sku      VARCHAR(50),
    nombre          VARCHAR(255),
    descripcion     TEXT,
    caracteristicas JSON,
    precio_venta    NUMERIC(10,2),
    stock           INTEGER,
    vigente         BOOLEAN,
    PRIMARY KEY (id_producto),
    CONSTRAINT uk_producto_sku UNIQUE (codigo_sku),
    CONSTRAINT fk_producto_marca FOREIGN KEY (id_marca)
        REFERENCES marca (id_marca) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria (id_categoria) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_producto_precio CHECK (precio_venta > 0),
    CONSTRAINT chk_producto_stock  CHECK (stock >= 0)
);

CREATE TABLE producto_imagen (
    id_producto_imagen BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_producto        BIGINT,
    url_imagen         VARCHAR(500),
    es_principal       BOOLEAN,
    orden              INTEGER DEFAULT 0,
    etiqueta           VARCHAR(100) DEFAULT 'Vista Principal',
    PRIMARY KEY (id_producto_imagen),
    CONSTRAINT fk_imagen_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE producto_proveedor (
    id_producto        BIGINT NOT NULL,
    id_proveedor       BIGINT NOT NULL,
    precio_compra      NUMERIC(10,2),
    tiempo_pedido_dias INTEGER,
    PRIMARY KEY (id_producto, id_proveedor),
    CONSTRAINT fk_pp_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_pp_proveedor FOREIGN KEY (id_proveedor)
        REFERENCES proveedor (id_proveedor) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_pp_precio CHECK (precio_compra > 0),
    CONSTRAINT chk_pp_tiempo CHECK (tiempo_pedido_dias >= 0)
);


-- ==============================================================
--  5 · CARRITO, VENTAS Y PAGOS
-- ==============================================================

CREATE TABLE carrito (
    id_carrito    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente    BIGINT,
    fecha_carrito TIMESTAMP,
    PRIMARY KEY (id_carrito),
    CONSTRAINT fk_carrito_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE detalle_carrito (
    id_detalle_carrito BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_carrito         BIGINT,
    id_producto        BIGINT,
    cantidad           INTEGER,
    PRIMARY KEY (id_detalle_carrito),
    CONSTRAINT fk_dc_carrito FOREIGN KEY (id_carrito)
        REFERENCES carrito (id_carrito) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_dc_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_dc_cantidad CHECK (cantidad > 0)
);

CREATE TABLE venta (
    id_venta        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cliente      BIGINT,
    id_empleado     BIGINT,
    estado          VARCHAR(50),
    fecha_venta     TIMESTAMP,
    subtotal        NUMERIC(10,2),
    igv             NUMERIC(10,2),
    total           NUMERIC(10,2),
    direccion_envio VARCHAR(255),
    PRIMARY KEY (id_venta),
    CONSTRAINT fk_venta_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_venta_empleado FOREIGN KEY (id_empleado)
        REFERENCES empleado (id_empleado) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_venta_totales CHECK (subtotal >= 0 AND igv >= 0 AND total > 0)
);

CREATE TABLE detalle_venta (
    id_detalle_venta BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_venta         BIGINT,
    id_producto      BIGINT,
    cantidad         INTEGER,
    precio_unitario  NUMERIC(10,2),
    sub_total_venta  NUMERIC(10,2),
    PRIMARY KEY (id_detalle_venta),
    CONSTRAINT fk_dv_venta FOREIGN KEY (id_venta)
        REFERENCES venta (id_venta) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_dv_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_dv_cantidad CHECK (cantidad > 0 AND precio_unitario > 0 AND sub_total_venta > 0)
);

CREATE TABLE pago (
    id_pago          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_venta         BIGINT,
    id_medio_pago    BIGINT,
    monto_pago       NUMERIC(10,2),
    fecha_pago       TIMESTAMP,
    codigo_operacion VARCHAR(50),
    estado_pago      VARCHAR(50),
    PRIMARY KEY (id_pago),
    CONSTRAINT fk_pago_venta FOREIGN KEY (id_venta)
        REFERENCES venta (id_venta) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_pago_medio_pago FOREIGN KEY (id_medio_pago)
        REFERENCES medio_pago (id_medio_pago) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_pago_monto CHECK (monto_pago > 0)
);


