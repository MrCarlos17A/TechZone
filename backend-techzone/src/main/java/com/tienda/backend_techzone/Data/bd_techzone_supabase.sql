-- Que roles pueden ver cada entrada. Sin filas = visible para todos.
CREATE TABLE ayuda_rol (
    id_ayuda BIGINT NOT NULL,
    id_rol   BIGINT NOT NULL,
    PRIMARY KEY (id_ayuda, id_rol),
